"""T4 tables and the T4 part of REPORT_SNIPPET.md (plan stage 4c). Every
number is recomputed from the cell's raw records (``part_a.jsonl``,
``part_b.jsonl``) with the current :mod:`trainmetrics.metrics_t4`, so a later
fix to the summary applies to an earlier run (reviews a0ddeaa, 51f1be2)."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

from .csvout import ok_cells, write_csv
from .metrics_t4 import summarize_t4
from .metrics_t5 import load_samples
from .metrics_t12 import p50, p95


def load_t4_cells(results: Path) -> List[Dict[str, Any]]:
    """Every finished (ok) T4 cell under ``<results>/t4/rep*``."""
    cells: List[Dict[str, Any]] = []
    for d, m in ok_cells(results, "t4/rep*/manifest.json"):
        cells.append(
            {
                "manifest": m,
                "part_a": load_samples(d / "part_a.jsonl"),
                "part_b": load_samples(d / "part_b.jsonl"),
            }
        )
    return cells


def build_times(cell: Dict[str, Any]) -> Dict[str, Any]:
    """Cold build wall times (p50 / p95 s) over the builds that ran; cached
    verdicts (review a0ddeaa S1) are counted, not timed."""
    colds = [a.get("cold") or {} for a in cell["part_a"]] + [
        r.get("cold") or {} for r in cell["part_b"] if r["variant"] != "unchanged"
    ]
    # a block with nothing to mutate (no fact name to replace) has no build
    colds = [c for c in colds if c]
    ran = [
        float(c["wall_s"])
        for c in colds
        if c.get("wall_s") is not None and not c.get("cached")
    ]
    return {
        "builds": len(colds),
        "cached": sum(1 for c in colds if c.get("cached")),
        "unanswered": sum(1 for c in colds if c and c.get("accepted") is None),
        "wall_p50_s": None if not ran else round(float(p50(ran) or 0), 2),
        "wall_p95_s": None if not ran else round(float(p95(ran) or 0), 2),
    }


def cause(error: Optional[str]) -> str:
    """The telling line of a cold build's error: the last ``***`` line (the
    tail ends with "Unfinished session(s)" and the elapsed time), else the
    last line."""
    lines = [x.strip() for x in (error or "").splitlines() if x.strip()]
    marked = [x for x in lines if x.startswith("***")]
    return (marked or lines or [""])[-1][:140]


def _f(v: Any, nd: int = 3) -> str:
    return "-" if v is None else f"{float(v):.{nd}f}"


def _pairs(xs: Sequence[Any]) -> str:
    return ", ".join(f"{s}#{i}" for s, i in xs) or "none"


def _safety(b: Dict[str, Any]) -> str:
    """The two kinds of safety finding, named apart (review 05323b4 S1)."""
    mutants = [b[v] for v in ("sorry", "truncated", "wrong_fact")]
    cold_rejected = [x for r in mutants for x in r["safety_findings"]]
    unsound = [x for r in mutants for x in r["both_unsound"]]
    return (
        f"Safety findings: a mutant proved in-session and rejected cold: {_pairs(cold_rejected)}; "
        f"a `sorry` or truncated mutant accepted by both (both unsound): {_pairs(unsound)}. "
    )


def snippet_t4(cell: Dict[str, Any]) -> Tuple[str, List[Dict[str, Any]]]:
    """The T4 paragraph and the per-variant rows (for the CSV)."""
    m = cell["manifest"]
    s = summarize_t4(cell["part_a"], cell["part_b"])
    a, b = s["part_a"], s["part_b"]
    bt = build_times(cell)
    t4 = m.get("t4") or {}
    lines = [
        f"## T4 agreement, rep {m.get('rep')} (generated by trainmetrics.analyze)",
        "",
        f"Part A, the corpus as written: {a['files']} files; the in-session verdict is the census's "
        "(a W = 1 replay at the maximum budget, 600 s per block, a session per file), the cold one a "
        f"whole-file `isabelle build` on the heap. {a['agree']} of {a['judged']} agree "
        f"({a['both_proved']} proved both ways); {a['in_session_only']} proved in-session but rejected "
        f"cold, {a['cold_only']} the reverse; {a['cold_unanswered']} cold builds did not answer.",
    ]
    for d in a["disagreements"]:
        first = d.get("first_unproved") or {}
        lines.append(
            f"- {d['stem']}: in-session {'proved' if d['in_session_proved'] else 'not proved'}"
            + (f" (first unproved block {first.get('index')})" if first else "")
            + f", cold {'accepted' if d['cold_accepted'] else 'rejected'}: "
            + f"`{cause(d.get('cold_error'))}`"
        )
    lines += [
        "",
        f"Part B, the mutation suite: {len(m.get('picks') or [])} census-proved theorem blocks (seeded), "
        "each in four variants, one mutation per cold build. A mutant is judged only where its "
        "file as written proves in-session and builds cold (else *baseline failed*). For `sorry` and "
        "truncated, both checkers accepting is a safety finding (both unsound); for a wrong fact it "
        "means the mutator missed (ineffective, out of the rates). The wrong fact is mostly a fact "
        "name; occasionally another name (a locale in `interpret`), still an undefined name to both.",
        "",
        "| variant | blocks | n/a | apart | baseline failed | both accept | in-session only | cold only "
        "| both reject | in-session reject rate | cold reject rate |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    rows: List[Dict[str, Any]] = []
    for v, r in b.items():
        rows.append(
            {
                "rep": m.get("rep"),
                "variant": v,
                **{
                    k: (json.dumps(x) if isinstance(x, list) else x)
                    for k, x in r.items()
                },
            }
        )
        lines.append(
            f"| {v} | {r['blocks']} | {r['not_applicable']} | {r['apart']} | {r.get('baseline_failed', '-')} | "
            f"{r['both_accept']} | {r['in_session_only']} | {r['cold_only']} | {r['both_reject']} | "
            f"{_f(r.get('in_session_reject_rate'))} | {_f(r.get('cold_reject_rate'))} |"
        )
    lines += [
        "",
        _safety(b)
        + f"Ineffective wrong-fact mutants (for inspection): {_pairs(b['wrong_fact']['ineffective'])}. "
        "The unchanged row repeats part A per sampled block: its disagreements are part A's causes.",
        "",
        f"Cold builds: {bt['builds']} ({bt['cached']} served from the server's cache, not timed; "
        f"{bt['unanswered']} unanswered), wall p50 {_f(bt['wall_p50_s'], 1)} s, p95 "
        f"{_f(bt['wall_p95_s'], 1)} s, at most {m.get('builds_bigstep_max_seen')} seen in flight "
        f"(build_concurrency {t4.get('build_concurrency')}).",
    ]
    if m.get("warning"):
        lines += ["", f"WARNING (from the cell): {m['warning']}"]
    return "\n".join(lines) + "\n", rows


def write_t4(results: Path, tables: Path) -> Tuple[str, int]:
    """The T4 tables and snippet text, a paragraph per repeat ("" without a
    T4 cell; review 05323b4 S2); (text, cells)."""
    cells = load_t4_cells(results)
    texts: List[str] = []
    agreement: List[Dict[str, Any]] = []
    mutations: List[Dict[str, Any]] = []
    for cell in cells:
        text, rows = snippet_t4(cell)
        texts.append(text)
        rep = cell["manifest"].get("rep")
        agreement += [{"rep": rep, **a} for a in cell["part_a"]]
        mutations += rows
    if cells:
        write_csv(tables / "t4_agreement.csv", agreement)
        write_csv(tables / "t4_mutations.csv", mutations)
    return "\n".join(texts), len(cells)
