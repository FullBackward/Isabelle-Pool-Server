def _repeat_points(ax: Any, rows: List[Dict[str, Any]]) -> None:
    """Every repeat's two rates as small points, so the spread shows."""
    for key, color in (("chunks_per_min", "C0"), ("chunks_per_min_incl_setup", "C1")):
        pts = [(int(r["workers"]), r[key]) for r in rows if r.get(key) is not None]
        if pts:
            ax.scatter(
                [x for x, _ in pts], [y for _, y in pts], s=10, color=color, alpha=0.5
            )


def _plot_t1(
    series: List[Dict[str, Any]], rows: Optional[List[Dict[str, Any]]], out: Path
) -> Optional[str]:
    """Throughput vs W: linear scaling from W = 1, the two rates, every repeat
    as a point (the CPU curve was dropped from the figure on 2026-10-28; the
    series keeps host_cpu_util)."""
    import matplotlib.pyplot as plt  # pylint: disable=import-outside-toplevel

    if not series:
        return None
    fig, ax = plt.subplots(figsize=(6, 4))
    ws = [s["workers"] for s in series]
    base = next((s["chunks_per_min"] for s in series if s["workers"] == 1), None)
    if base:
        ax.plot(
            ws,
            [w * base for w in ws],
            color="grey",
            ls=":",
            label="linear scaling from W = 1",
        )
    ax.plot(
        ws, [s["chunks_per_min"] for s in series], marker="o", label="verification only"
    )
    ax.plot(
        ws,
        [s["chunks_per_min_incl_setup"] for s in series],
        marker="s",
        label="end to end, session starts included",
    )
    _repeat_points(ax, rows or [])
    ax.set_xscale("log", base=2)
    ax.set_xticks(ws)
    ax.set_xticklabels([str(w) for w in ws])
    ax.set_xlabel("workers W")
    ax.set_ylabel("verified chunks / min")
    ax.grid(True, alpha=0.3)
    ax.legend(loc="upper left")
    fig.tight_layout()
    path = out / "t1_throughput.png"
    fig.savefig(path, dpi=120)
    plt.close(fig)
    return str(path)


def plots(
    series: List[Dict[str, Any]],
    t2: List[Dict[str, Any]],
    out: Path,
    rows: Optional[List[Dict[str, Any]]] = None,
) -> List[str]:
    """Throughput vs W (linear scaling from W = 1, every repeat as a point) and
    T2 latency per class; skipped without matplotlib (as in memscale)."""
    try:
        import matplotlib  # pylint: disable=import-outside-toplevel

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt  # pylint: disable=import-outside-toplevel
    except ImportError:
        print("plots skipped: matplotlib is not installed (pip install -e '.[eval]')")
        return []
    made: List[str] = []
    out.mkdir(parents=True, exist_ok=True)
    t1 = _plot_t1(series, rows, out)
    if t1:
        made.append(t1)
    if t2:
        fig, ax = plt.subplots(figsize=(6, 4))
        for w in sorted({r["workers"] for r in t2}):
            rs = [r for r in t2 if r["workers"] == w]
            ax.plot(
                [r["class"] for r in rs],
                [r["latency_p50_s"] for r in rs],
                marker="o",
                label=f"W={w} p50",
            )
            ax.plot(
                [r["class"] for r in rs],
                [r["latency_p95_s"] for r in rs],
                marker="x",
                ls=":",
                label=f"W={w} p95",
            )
        ax.set_xlabel("chunk size (census commands)")
        ax.set_ylabel("verify_chunk latency (s)")
        ax.set_yscale("log")
        ax.grid(True, alpha=0.3)
        ax.legend()
        fig.tight_layout()
        path = out / "t2_latency.png"
        fig.savefig(path, dpi=120)
        plt.close(fig)
        made.append(str(path))
    return made


def _f(v: Optional[float], nd: int = 1) -> str:
    return "-" if v is None else f"{v:.{nd}f}"


def snippet_t12(
    series: List[Dict[str, Any]], t2: List[Dict[str, Any]], census: Dict[str, Any]
) -> str:
    """The T1/T2 part of REPORT_SNIPPET.md."""
    tot = census.get("totals") or {}
    lines = [
        "## T1 throughput and T2 verify latency (generated by trainmetrics.analyze)",
        "",
        f"Census `{str(census.get('census_id'))[:12]}`: {tot.get('files')} files, "
        f"{tot.get('blocks')} blocks, {tot.get('commands')} commands "
        f"({tot.get('partial_count_blocks', 0)} with a partial count, "
        f"{zero_count_blocks(census)} with no command; both left out of the size classes).",
        "",
        "Census work rate = census time of the cell's files / cell window (W = 1 replays "
        "of the same files running in parallel); speedup and efficiency are on it, so they "
        "do not depend on the file mix. Latencies exclude timed-out calls (rate beside).",
        "",
        "Every file runs on a session acquired with its own imports (IPS fixes a session's "
        "context at acquisition), so a cold acquisition precedes every file: the rate "
        "including acquire + enter sits well below the verify-only rate, by the acquire "
        "share shown — that is the cost of per-file contexts, not of verification. Files "
        "whose acquisition was refused (after retries) are left out of the census-relative "
        "numbers and counted as skipped.",
        "",
        "| W | census work rate | speedup | efficiency | chunks/min (verify only) | commands/min | "
        "chunks/min (incl. acquire + enter) | acquire share | skipped files | slowdown vs census | "
        "p50 / p95 s | timeout rate | host CPU % | PSS peak GB |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    if any(s.get("external") for s in series):
        lines.insert(
            len(lines) - 2,
            "Cells run against an external server (`--ips-external`) show no host CPU or PSS: "
            "the server's tree holds other clients' sessions too.\n",
        )
    for s in series:
        ext = s.get("external")  # other clients in the tree: no resource columns
        util = None if ext else s.get("host_cpu_util")
        pss = None if ext else s.get("pss_peak_mb")
        lines.append(
            f"| {s['workers']} | {_f(s['census_work_rate'], 2)} | {_f(s['speedup'], 2)} | "
            f"{_f(s['efficiency'], 2)} | {_f(s['chunks_per_min'])} | "
            f"{_f(s['commands_per_min'])} | {_f(s['chunks_per_min_incl_setup'])} | "
            f"{_f(s.get('acquire_share'), 2)} | {_f(s.get('skipped_files'), 0)} | "
            f"{_f(s['slowdown_vs_census'], 2)} | "
            f"{_f(s['latency_p50_s'], 3)} / {_f(s['latency_p95_s'], 3)} | "
            f"{_f(s['timeout_rate'], 4)} | {_f(100 * util if util is not None else None)} | "
            f"{_f(pss / 1024 if pss else None)} |"
        )
    lines += [
        "",
        "| W | chunk size | n | p50 s | p95 s | timeout rate | ms per command (p50) |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in t2:
        lines.append(
            f"| {r['workers']} | {r['class']} | {r['n']} | {_f(r['latency_p50_s'], 3)} | "
            f"{_f(r['latency_p95_s'], 3)} | {_f(r['timeout_rate'], 4)} | "
            f"{_f(r['ms_per_command_p50'], 1)} |"
        )
    floor = next(
        (
            r
            for r in t2
            if r["workers"] == min(x["workers"] for x in t2) and r["class"] == "1"
        ),
        None,
    )
    if floor:
        lines += [
            "",
            f"Per-call floor (p50 of single-command chunks at W={floor['workers']}): "
            f"{_f(floor['latency_p50_s'], 3)} s.",
        ]
    return "\n".join(lines) + "\n"


def write_t12(
    results: Path, census: Dict[str, Any], cfg: Dict[str, Any], tables: Path
) -> Tuple[str, int, int, int]:
    """The T1 / T2 tables, plots and snippet text with the PIDE MCP row;
    (text, T1 cells, plots, PIDE cells)."""
    cells = load_t1_cells(results)
    rows = [summarize_cell(c, census) for c in cells]
    series = series_t1(rows)
    t2 = t2_table(cells, census, [int(w) for w in cfg.get("t2_workers", [1, 8])])
    write_csv(tables / "t1_cells.csv", rows)
    write_csv(tables / "t1_series.csv", series)
    write_csv(tables / "t2_latency.csv", t2)
    made = plots(series, t2, results / "plots", rows)
    text = snippet_t12(series, t2, census) if cells else ""  # no T1 cell: no T1 tables
    ips_env = next((c.get("ips_env") for c in cells if c.get("ips_env")), None)
    pide_text, n_pide = write_pide(results, census, tables, series, ips_env)
    return "\n".join(x for x in (text, pide_text) if x), len(rows), len(made), n_pide


def write_all(
    results: Path, census: Dict[str, Any], cfg: Dict[str, Any], tables: Path
) -> Tuple[str, str, int]:
    """Every experiment's tables, plots and snippet text; (the snippet, the
    cell counts, the plots). The paragraphs follow the report's questions
    (its Table: rollouts per hour, latency, branch cost, agreement, bounded
    step): T6 answers the first, T1 is the step rate and its scaling (with the
    PIDE row), T2 a by-product (D11), then T3, T4, T5."""
    t12_text, n_t1, t12_plots, n_pide = write_t12(results, census, cfg, tables)
    parts: Dict[str, Tuple[str, int, int]] = {  # (text, cells, plots)
        "T1": (t12_text, n_t1, t12_plots),
        "PIDE": ("", n_pide, 0),  # its paragraph is in T1's text
        "T5": (*write_t5(results, census, tables), 0),
        "T4": (*write_t4(results, tables), 0),
        "T3": write_t3(results, tables),
        "T6": write_t6(results, tables),
    }
    order = ("T6", "T1", "T3", "T4", "T5")
    counts = ", ".join(f"{p[1]} {name} cells" for name, p in parts.items())
    return (
        "\n".join(parts[k][0] for k in order if parts[k][0]),
        counts,
        sum(p[2] for p in parts.values()),
    )


def main(argv: Optional[Sequence[str]] = None) -> int:
    """CLI entry point."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", default=str(EXPERIMENT_DIR / "config.yaml"))
    ap.add_argument("--results", default=str(EXPERIMENT_DIR / "results"))
    ap.add_argument(
        "--census", default=None, help="default: <results>/census/census.json"
    )
    args = ap.parse_args(argv)
    results = Path(args.results)
    census = load_census(args.census or str(results / "census" / "census.json"))
    tables = results / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    text, counts, n_plots = write_all(results, census, load_config(args.config), tables)
    with open(results / "REPORT_SNIPPET.md", "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"{counts} -> {tables}, {n_plots} plots, {results}/REPORT_SNIPPET.md")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
